local DICTS = { false, FR, RU, ZH, PT, ES, AR }

-- reads lang=N from the settings file (called when a screen is built)
function L.load()
    local n = 1
    pcall(function()
        local f = io.open("jupiter/IO/br95_settings.txt", "r")
        if not f then return end
        local text = f:read("*a"); f:close()
        n = tonumber(text:match("lang=(%d+)")) or 1
    end)
    if n < 1 or n > #L.NAMES then n = 1 end
    L.lang = n
    return n
end

function L.T(text, ...)
    local d = DICTS[L.lang]
    local out = (d and d[text]) or text
    if select("#", ...) > 0 then
        local ok, s = pcall(string.format, out, ...)
        if ok then return s end
        return string.format(text, ...)
    end
    return out
end

L.load()
